// KVKK notice and disclaimer check (SPEC Phase 7: "disclaimer and KVKK text check"). It cannot say whether the text
// is legally enough; that is the lawyer's job (docs/Phase7_KVKK_Checklist.md). It makes sure the built pages still
// carry every element the notice is meant to have, so nobody removes a section by accident, and that the notice names
// every outside service the site can send data to.
//
//   node scripts/kvkk-check.mjs            check dist/ (run npm run build first); exit 1 on a missing element
//   node scripts/kvkk-check.mjs --print    write docs/Phase7_KVKK_Notice_Text.md (TR and EN side by side, for the lawyer)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SITE_CONFIG } from '../src/lib/site-config.mjs';

const SECTIONS = ['controller', 'data', 'purpose', 'basis', 'abroad', 'retention', 'rights', 'cookies'];
const PATHS = { tr: 'tr/aydinlatma-metni/index.html', en: 'en/privacy-notice/index.html' };
const CONTACT = { tr: 'tr/iletisim/index.html', en: 'en/contact/index.html' };

const strip = (html) =>
  html
    .replace(/<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&amp;/g, '&')
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

/**
 * @param {{ notice: string, contact: string, home: string, tr: Record<string,string>, en: Record<string,string>, lang: 'tr'|'en', services: string[] }} input
 * @returns {string[]} problems, empty when every element is there
 */
export function checkNotice({ notice, contact, home, dict, lang, services }) {
  const problems = [];
  const text = strip(notice);
  for (const s of SECTIONS) {
    const heading = dict[`privacy.${s}.h`];
    if (!heading || !text.includes(strip(heading))) problems.push(`${lang}: notice has no "${heading ?? `privacy.${s}.h`}" section`);
    const body = dict[`privacy.${s}.p`];
    // Compare the text up to the first {placeholder}: the controller sentence is filled from site-config at build time.
    if (body && !text.includes(strip(body).split('{')[0].slice(0, 60).trim())) problems.push(`${lang}: the "${s}" section text is missing`);
  }
  for (const svc of services) if (!text.includes(svc)) problems.push(`${lang}: notice does not name ${svc}, a service the site sends data to`);
  if (!/(madde|article)\s*5/i.test(text)) problems.push(`${lang}: notice does not cite the legal basis article (KVKK 5)`);
  if (!/(madde|article)\s*11/i.test(text)) problems.push(`${lang}: notice does not cite the rights article (KVKK 11)`);
  // The form: required consent checkbox that links to the notice, and a statement that the data goes abroad.
  if (!/<input[^>]*id="c-consent"[^>]*required|<input[^>]*required[^>]*id="c-consent"/.test(contact)) problems.push(`${lang}: the contact form has no required consent checkbox`);
  const link = lang === 'tr' ? 'aydinlatma-metni' : 'privacy-notice';
  if (!new RegExp(`href="[^"]*${link}/?"`).test(contact)) problems.push(`${lang}: the contact form does not link to the notice`);
  if (!strip(contact).includes(strip(dict['contact.consentAfter']).slice(0, 40))) problems.push(`${lang}: the consent sentence is missing from the form`);
  // The disclaimer: on the page, with the three things it must say.
  const disclaimer = dict['footer.disclaimer'];
  if (!strip(home).includes(strip(disclaimer))) problems.push(`${lang}: the footer disclaimer is not on the page`);
  for (const word of ['Cisco', 'Ingram Micro']) if (!disclaimer.includes(word)) problems.push(`${lang}: disclaimer does not mention ${word}`);
  return problems;
}

/** Markdown for the lawyer: every notice string in both languages, then the form consent and the footer. */
export function noticeMarkdown(tr, en, today = new Date().toISOString().slice(0, 10)) {
  const keys = Object.keys(tr).filter((k) => /^privacy\./.test(k));
  const row = (k) => `| \`${k}\` | ${tr[k].replace(/\|/g, '\\|')} | ${en[k].replace(/\|/g, '\\|')} |`;
  const extra = ['contact.consentBefore', 'contact.consentLink', 'contact.consentAfter', 'contact.notOrder', 'footer.disclaimer'];
  return [
    '# KVKK notice text, Turkish and English side by side',
    '',
    `Generated ${today} by \`npm run kvkk:text\` from \`src/i18n/tr.json\` and \`en.json\`. Do not edit this file: corrections go into those files (or through the Turkish review kit).`,
    '',
    '`{name}` and `{email}` are filled from `src/lib/site-config.mjs` (the controller). The consent sentence on the form is "consentBefore" + link text + "consentAfter".',
    '',
    '## The notice (page "Aydınlatma Metni (KVKK)")',
    '',
    '| Key | Türkçe | English |',
    '| --- | --- | --- |',
    ...keys.map(row),
    '',
    '## Consent sentence on the form, form note and footer',
    '',
    '| Key | Türkçe | English |',
    '| --- | --- | --- |',
    ...extra.map(row),
    '',
    '## What the form sends (Web3Forms)',
    '',
    'Name, email, company (optional), message, the shortlist only if the box is ticked (model names and part numbers), the address of the page the form was sent from and the site language. A hidden spam field and a three second minimum are used against bots.',
    '',
    '## What the page view counter sends (GoatCounter)',
    '',
    'Page address without the part after "?", page title, screen width, referring site name, a robot flag, and the name (only) of events such as "added to shortlist". The counter script is served from this site. Nothing is sent when Do Not Track or Global Privacy Control is on.',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const tr = JSON.parse(readFileSync('src/i18n/tr.json', 'utf8'));
  const en = JSON.parse(readFileSync('src/i18n/en.json', 'utf8'));
  if (process.argv.includes('--print')) {
    writeFileSync('docs/Phase7_KVKK_Notice_Text.md', noticeMarkdown(tr, en));
    console.log('wrote docs/Phase7_KVKK_Notice_Text.md');
    process.exit(0);
  }
  const dist = process.env.DIST_DIR ?? 'dist';
  const services = ['Web3Forms', 'GoatCounter'];
  // The services named above must be the ones the site is actually configured to use.
  const problems = [];
  if (!SITE_CONFIG.web3forms.endpoint.includes('web3forms.com')) problems.push('site-config: the form no longer posts to Web3Forms; update the notice and this check');
  if (!SITE_CONFIG.goatcounter.endpoint.includes('goatcounter.com')) problems.push('site-config: analytics no longer uses GoatCounter; update the notice and this check');
  for (const lang of ['tr', 'en']) {
    const read = (p) => (existsSync(`${dist}/${p}`) ? readFileSync(`${dist}/${p}`, 'utf8') : '');
    const [notice, contact, home] = [read(PATHS[lang]), read(CONTACT[lang]), read(`${lang}/index.html`)];
    if (!notice || !contact) {
      problems.push(`${lang}: ${dist}/${PATHS[lang]} or ${dist}/${CONTACT[lang]} is missing (run npm run build)`);
      continue;
    }
    problems.push(...checkNotice({ notice, contact, home, dict: lang === 'tr' ? tr : en, lang, services }));
  }
  if (problems.length) {
    for (const p of problems) console.log(`  ${p}`);
    console.log(`kvkk-check FAILED (${problems.length})`);
    process.exit(1);
  }
  console.log('kvkk-check passed: both notices carry every section, name Web3Forms and GoatCounter, cite KVKK 5 and 11; the form has its required consent box and link; the disclaimer is on the page');
}
